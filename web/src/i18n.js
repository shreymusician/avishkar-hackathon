export const DICTIONARY = { en, kn, hi };

/** Looks up `key` in `lang` (falling back to English) and fills in {placeholders}. */
export function translate(lang, key, vars) {
  let text = DICTIONARY[lang]?.[key] ?? en[key] ?? key;
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
